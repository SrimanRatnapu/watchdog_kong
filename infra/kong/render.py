"""Render infra/kong/kong.yml from kong.template.yml.

Values come from the environment, then the repo-root .env. A missing gateway key (DL_GATEWAY_KEY_<ROLE>) is
generated and appended to .env, so Kong and Watchdog read the same keys. kong.yml holds those keys: it is gitignored.

    python infra/kong/render.py            # write infra/kong/kong.yml
    python infra/kong/render.py --check    # fail if anything is unset; write nothing
"""
from __future__ import annotations

import argparse
import os
import re
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TEMPLATE, OUT, ENV_FILE = HERE / "kong.template.yml", HERE / "kong.yml", REPO / ".env"
ROLES = ("triage", "agents", "examiner", "translation", "eval")
DEFAULTS = {"KONG_UPSTREAM_URL": "https://api.anthropic.com", "KONG_RATE_PER_MINUTE": "600"}
PLACEHOLDER = re.compile(r"\$\{([A-Z0-9_]+)\}")


def read_env_file(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        out[key.strip()] = value.split(" #", 1)[0].strip().strip('"').strip("'")
    return out


def values(env_file: Path = ENV_FILE, create_keys: bool = True) -> dict[str, str]:
    vals = {**DEFAULTS, **read_env_file(env_file), **{k: v for k, v in os.environ.items() if v}}
    missing = [f"DL_GATEWAY_KEY_{r.upper()}" for r in ROLES if not vals.get(f"DL_GATEWAY_KEY_{r.upper()}")]
    if missing and create_keys:
        new = {k: "wd-" + secrets.token_hex(16) for k in missing}
        with env_file.open("a") as f:
            f.write("\n# Kong gateway keys, one per role (generated by infra/kong/render.py)\n")
            f.writelines(f"{k}={v}\n" for k, v in new.items())
        vals.update(new)
        print(f"generated {len(new)} gateway key(s) into {env_file}", file=sys.stderr)
    return vals


def render(template: str, vals: dict[str, str]) -> str:
    unset = sorted({m for m in PLACEHOLDER.findall(template) if not vals.get(m)})
    if unset:
        raise SystemExit(f"unset: {', '.join(unset)}")
    return PLACEHOLDER.sub(lambda m: vals[m.group(1)], template)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="validate only; write nothing")
    args = ap.parse_args(argv)
    text = render(TEMPLATE.read_text(), values(create_keys=not args.check))
    if not args.check:
        OUT.write_text(text)
        OUT.chmod(0o644)       # Kong runs as its own user inside the container
        print(f"wrote {OUT.relative_to(REPO)}", file=sys.stderr)


if __name__ == "__main__":
    main()
